// keccak256(abi.encode(scope, recipient, challenge)): three 32-byte words, the address left-padded.
fn bind_hash(scope: &[u8; 32], recipient: &[u8; 20], challenge: &[u8; 32]) -> [u8; 32] {
    let mut m = Vec::with_capacity(96);
    m.extend_from_slice(scope);
    m.extend_from_slice(&[0u8; 12]);
    m.extend_from_slice(recipient);
    m.extend_from_slice(challenge);
    Keccak256Hash {}.hash_iter(m)
}

// EIP-55 checksummed hex (Solidity rejects address literals without it).
fn to_checksum(a: &[u8; 20]) -> String {
    let lower = hex(a);
    let h: [u8; 32] = Keccak256Hash {}.hash_iter(lower.bytes());
    lower
        .chars()
        .enumerate()
        .map(|(i, c)| {
            let nib = (h[i / 2] >> (if i % 2 == 0 { 4 } else { 0 })) & 0xf;
            if c.is_ascii_alphabetic() && nib >= 8 { c.to_ascii_uppercase() } else { c }
        })
        .collect()
}

