// Vectors for the on-chain record hashing (contracts/src/Reputation.sol), from the circuit's own functions: records
// (fields in the order completed, clients, volume, rejected, expired, tier, firstDay, epoch), their digests and leaves,
// scope elements, binding values and one whole set of public values.
fn rep_vectors(out: &mut String) {
    let mut rng = StdRng::seed_from_u64(0x0BEB_7EC5);
    writeln!(out, "// SPDX-License-Identifier: MIT").unwrap();
    writeln!(out, "pragma solidity ^0.8.24;").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "// Generated by tools/src/bin/rep.rs from ostra-swap-circuit (Plonky3 0.8.0). Do not edit.").unwrap();
    writeln!(out, "library RepVectors {{").unwrap();
    let records = [
        Record { completed: 0, clients: 0, volume: 0, rejected: 0, expired: 0, tier: 0, first_day: 0, epoch: 0 },
        Record {
            completed: (1 << 19) - 1,
            clients: (1 << 19) - 1,
            volume: u128::MAX,
            rejected: (1 << 16) - 1,
            expired: (1 << 16) - 1,
            tier: 3,
            first_day: (1 << 29) - 1,
            epoch: (1 << 30) - 1,
        },
        Record { completed: 212, clients: 57, volume: 12_345_678_901, rejected: 4, expired: 2, tier: 2, first_day: 31, epoch: 6 },
    ];
    for (case, r) in records.iter().enumerate() {
        let id = digest_from(&mut rng);
        record_line(out, &format!("record{case}"), r);
        writeln!(out, "    bytes32 internal constant IDC_{case} = {};", b32(&pack_digest(&id))).unwrap();
        writeln!(out, "    bytes32 internal constant RECORD_{case} = {};", b32(&pack_digest(&r.digest()))).unwrap();
        writeln!(out, "    bytes32 internal constant LEAF_{case} = {};", b32(&pack_digest(&r.leaf(&id)))).unwrap();
    }
    for case in 0..3 {
        let scope = if case == 0 { [0u8; 32] } else { bytes32_from(&mut rng) };
        let e = scope_elements(&scope);
        writeln!(out, "    bytes32 internal constant SCOPE_{case} = 0x{};", hex(&scope)).unwrap();
        let es: Vec<String> = e.iter().map(|x| canon(*x).to_string()).collect();
        writeln!(out, "    function scopeElements{case}() internal pure returns (uint256[8] memory) {{ return [{}]; }}", arr(&es)).unwrap();
    }
    // A whole statement: a record in a tree, the verifier's scope, recipient, challenge and thresholds.
    let sk = digest_from(&mut rng);
    let r = records[2];
    let mut tree = Tree::new();
    for _ in 0..3 {
        tree.append(digest_from(&mut rng));
    }
    let index = tree.append(r.leaf(&idc(&sk)));
    let scope = bytes32_from(&mut rng);
    let recipient: [u8; 20] = core::array::from_fn(|_| rng.next_u32() as u8);
    let challenge = bytes32_from(&mut rng);
    let bh = bind_hash(&scope, &recipient, &challenge);
    let t = Thresholds { min_completed: 200, min_clients: 50, min_volume: 10_000_000_000, max_fail_permille: 50, min_tier: 2, max_first_day: 40 };
    let s = Rep { sk, record: r, index, path: tree.path(index), scope: scope_elements(&scope), thresholds: t, bind: bind_from_hash(&bh) };
    assert!(s.check().is_ok());
    let pv = s.public_values();
    writeln!(out, "    bytes32 internal constant ROOT = {};", b32(&pack_digest(&s.root()))).unwrap();
    writeln!(out, "    bytes32 internal constant PSEUDONYM = {};", b32(&pack_digest(&s.pseudonym()))).unwrap();
    writeln!(out, "    bytes32 internal constant SCOPE = 0x{};", hex(&scope)).unwrap();
    writeln!(out, "    address internal constant RECIPIENT = 0x{};", to_checksum(&recipient)).unwrap();
    writeln!(out, "    bytes32 internal constant CHALLENGE = 0x{};", hex(&challenge)).unwrap();
    writeln!(out, "    bytes32 internal constant BIND_HASH = 0x{};", hex(&bh)).unwrap();
    writeln!(out, "    uint256 internal constant EPOCH = {};", r.epoch).unwrap();
    writeln!(
        out,
        "    function thresholds() internal pure returns (uint256[6] memory) {{ return [uint256({}), {}, {}, {}, {}, {}]; }}",
        t.min_completed, t.min_clients, t.min_volume, t.max_fail_permille, t.min_tier, t.max_first_day
    )
    .unwrap();
    let pvs: Vec<String> = pv.iter().map(|x| canon(*x).to_string()).collect();
    writeln!(out, "    function publics() internal pure returns (uint256[{REP_PUBLIC}] memory) {{ return [{}]; }}", arr(&pvs)).unwrap();
    writeln!(out, "}}").unwrap();
}

// Sample statements: different records, thresholds (equality at each, the widest fields), tree positions and sizes.
fn samples() -> Vec<Rep> {
    let mut rng = StdRng::seed_from_u64(0x0BEB_A11E);
    let wide = Record {
        completed: (1 << 19) - 1,
        clients: (1 << 19) - 1,
        volume: u128::MAX,
        rejected: (1 << 16) - 1,
        expired: (1 << 16) - 1,
        tier: 3,
        first_day: (1 << 29) - 1,
        epoch: 2_000,
    };
    let cases: [(Record, Thresholds, usize); 4] = [
        (
            Record { completed: 12, clients: 6, volume: 150_000_000, rejected: 1, expired: 0, tier: 1, first_day: 3, epoch: 7 },
            Thresholds { min_completed: 10, min_clients: 5, min_volume: 100_000_000, max_fail_permille: 200, min_tier: 1, max_first_day: 30 },
            0,
        ),
        (
            wide,
            Thresholds {
                min_completed: wide.completed,
                min_clients: wide.clients,
                min_volume: wide.volume,
                max_fail_permille: 200,
                min_tier: 3,
                max_first_day: (1 << 29) - 1,
            },
            5,
        ),
        (
            Record { completed: 1, clients: 1, volume: 1_000_000, rejected: 0, expired: 0, tier: 0, first_day: 0, epoch: 0 },
            Thresholds { min_completed: 0, min_clients: 0, min_volume: 0, max_fail_permille: 1000, min_tier: 0, max_first_day: 0 },
            2,
        ),
        (
            Record { completed: 400, clients: 90, volume: 50_000_000_000, rejected: 3, expired: 1, tier: 3, first_day: 2, epoch: 104 },
            Thresholds { min_completed: 200, min_clients: 50, min_volume: 10_000_000_000, max_fail_permille: 11, min_tier: 3, max_first_day: 10 },
            33,
        ),
    ];
    cases
        .iter()
        .map(|&(record, thresholds, before)| {
            let sk = digest_from(&mut rng);
            let mut tree = Tree::new();
            for _ in 0..before {
                tree.append(digest_from(&mut rng));
            }
            let index = tree.append(record.leaf(&idc(&sk)));
            tree.append(digest_from(&mut rng));
            let scope = bytes32_from(&mut rng);
            let s = Rep {
                sk,
                record,
                index,
                path: tree.path(index),
                scope: scope_elements(&scope),
                thresholds,
                bind: bind_from_hash(&bytes32_from(&mut rng)),
            };
            assert_eq!(s.root(), tree.root());
            assert!(s.check().is_ok(), "sample meets its thresholds");
            s
        })
        .collect()
}

fn main() {
    let dir = std::env::args().nth(1).expect("usage: rep <contracts dir>");
    let air = RepAir::new();
    assert_eq!(BaseAir::<Val>::width(&air), REP_WIDTH);
    for (n, s) in samples().iter().enumerate() {
        let start = std::time::Instant::now();
        let (proof, pv) = prove_rep(s, test_seed(300 + n as u64)).expect("prove");
        let took = start.elapsed();
        assert!(verify_rep(&proof, &pv), "the proof verifies natively");
        let postcard = postcard::to_allocvec(&proof).expect("serialize");
        let f = flat::encode_width(&proof, REP_WIDTH);
        let back = flat::decode_width(&f, REP_WIDTH).expect("decode");
        assert_eq!(postcard::to_allocvec(&back).expect("serialize"), postcard, "flat layout round-trips");
        assert!(verify_rep(&back, &pv), "the decoded proof verifies natively");
        let zeros = f.iter().filter(|&&b| b == 0).count();
        println!(
            "rep {n}: prove {:?}, postcard {} bytes, flat {} bytes ({} zero), calldata gas {}",
            took,
            postcard.len(),
            f.len(),
            zeros,
            16 * (f.len() - zeros) + 4 * zeros
        );
        std::fs::write(format!("{dir}/test/data/rep_{n}.bin"), &f).expect("write proof");
        let pvb: Vec<u8> = pv.iter().flat_map(|x| x.as_canonical_u32().to_be_bytes()).collect();
        std::fs::write(format!("{dir}/test/data/rep_pub_{n}.bin"), &pvb).expect("write publics");
        if n < 2 {
            assert_eq!(oracle(&f, &pv), Some(true), "the oracle accepts the real proof");
            let hook = std::panic::take_hook();
            std::panic::set_hook(Box::new(|_| {}));
            let (cases, by_oracle, by_design) = tamper_cases(&f, &pv);
            std::panic::set_hook(hook);
            println!("rep {n}: tampered cases {by_oracle} rejected by Plonky3, {by_design} by design");
            std::fs::write(format!("{dir}/test/data/rep_tamper_{n}.bin"), &cases).expect("write tampered cases");
        }
    }
    // A real proof in which two FRI queries open the same input leaf (searched over prover seeds), with tampered
    // variants that change the second opening's row or salt.
    {
        let s = &samples()[0];
        let pv = s.public_values();
        let mut found = None;
        for seed in 400u64..4000 {
            let (proof, _) = prove_rep(s, test_seed(seed)).expect("prove");
            let rows = &proof.opening_proof.1.input_openings[0].opened_values;
            let dup = (0..NUM_QUERIES).flat_map(|a| (a + 1..NUM_QUERIES).map(move |b| (a, b))).find(|&(a, b)| rows[a] == rows[b]);
            if let Some(pair) = dup {
                found = Some((seed, proof, pair));
                break;
            }
        }
        let (seed, proof, (a, b)) = found.expect("a proof with a duplicate query");
        let f = flat::encode_width(&proof, REP_WIDTH);
        assert_eq!(oracle(&f, &pv), Some(true), "the duplicate-query proof verifies");
        std::fs::write(format!("{dir}/test/data/rep_dup.bin"), &f).expect("write proof");
        let l = layout(&f);
        let widths_all = batch_widths_for(REP_WIDTH);
        let mut out = Vec::new();
        let mut n = 0;
        for (batch, &(start, _)) in l.batches.iter().enumerate() {
            let ws = &widths_all[batch];
            let per: usize = ws.iter().map(|w| 4 * (w + SALT)).sum();
            for (what, at) in [("row", start + per * b + 8), ("salt", start + per * b + 4 * ws[0] + 4)] {
                let mut v = f.clone();
                let x = (u32::from_be_bytes([v[at], v[at + 1], v[at + 2], v[at + 3]]) + 1) % Val::ORDER_U32;
                v[at..at + 4].copy_from_slice(&x.to_be_bytes());
                let hook = std::panic::take_hook();
                std::panic::set_hook(Box::new(|_| {}));
                let verdict = oracle(&v, &pv);
                std::panic::set_hook(hook);
                assert_eq!(verdict, Some(false), "Plonky3 rejects a changed duplicate {what}");
                out.push(0u8);
                out.extend_from_slice(&(at as u32).to_be_bytes());
                out.extend_from_slice(&4u16.to_be_bytes());
                out.extend_from_slice(&v[at..at + 4]);
                out.push(1);
                out.push(0);
                n += 1;
            }
        }
        std::fs::write(format!("{dir}/test/data/rep_tamper_dup.bin"), &out).expect("write tampered cases");
        println!("duplicate queries {a} and {b} at prover seed {seed}: {n} tampered cases rejected by Plonky3");
    }
    let mut out = String::new();
    constants(&mut out);
    std::fs::write(format!("{dir}/src/RepConstants.sol"), out).expect("write constants");
    let mut out = String::new();
    parts_vectors(&mut out);
    std::fs::write(format!("{dir}/test/RepPartsVectors.sol"), out).expect("write part vectors");
    let mut out = String::new();
    rep_vectors(&mut out);
    std::fs::write(format!("{dir}/test/RepVectors.sol"), out).expect("write record vectors");
}
