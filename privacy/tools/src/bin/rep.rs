// (contracts/src/RepVerifier.sol), all derived from Plonky3 0.8.0 itself, as tools/src/bin/spend.rs does for the spend
// circuit:
//   1. proves sample reputation statements (circuit/src/rep.rs) and verifies them natively,
//   2. writes each proof in the flat calldata layout (contracts/test/data/rep_<n>.bin) with its public values
//      (rep_pub_<n>.bin, 43 big-endian u32),
//   3. decodes the layout back and checks it serializes to the same postcard bytes and verifies,
