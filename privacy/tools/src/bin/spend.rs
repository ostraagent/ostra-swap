// Records every byte observed through SerializingChallenger32, to capture the transcript seeds.
#[derive(Clone)]
struct Rec {
    log: Arc<Mutex<Vec<u8>>>,
    inner: HashChallenger<u8, Keccak256Hash, 32>,
}

impl CanObserve<u8> for Rec {
    fn observe(&mut self, value: u8) {
        self.log.lock().unwrap().push(value);
        self.inner.observe(value);
    }
}

impl CanSample<u8> for Rec {
    fn sample(&mut self) -> u8 {
        self.inner.sample()
    }
}

impl ByteGrindingChallenger for Rec {}

fn recorder() -> (SerializingChallenger32<Val, Rec>, Arc<Mutex<Vec<u8>>>) {
    let log = Arc::new(Mutex::new(Vec::new()));
    let rec = Rec { log: log.clone(), inner: HashChallenger::new(vec![], Keccak256Hash {}) };
    (SerializingChallenger32::new(rec), log)
}

fn arr(items: &[String]) -> String {
    let mut v = items.to_vec();
    v[0] = format!("uint256({})", v[0]);
    v.join(", ")
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{:02x}", x)).collect()
}

fn canon(v: Val) -> u32 {
    v.as_canonical_u32()
}

fn seeds() -> (Vec<u8>, Vec<u8>, Vec<u8>) {
    let air = SpendAir::new();
    let shape = StarkShape::new::<Val, _>(&air, 0, DEGREE_BITS, DEGREE_BITS - 1, QUOTIENT_CHUNKS, true, 0);
    let (mut ch, log) = recorder();
    shape.domain_separator::<Val, Challenge>().seed(&mut ch);
    let stark = log.lock().unwrap().clone();
    let pcs_shape = PcsShape {
        claimed_evaluation_counts: batch_widths()
            .iter()
            .zip(batch_points())
            .map(|(ws, ps)| ws.iter().zip(ps).map(|(&w, p)| vec![w; p]).collect())
            .collect(),
        batch_pow_bits: BATCH_POW_BITS,
    };
    let (mut ch, log) = recorder();
    pcs_shape.domain_separator::<Val, Challenge>().seed(&mut ch);
    let pcs = log.lock().unwrap().clone();
    let fri_shape = p3_fri::FriShape {
        log_arities: schedule(),
        final_poly_len: FINAL_POLY_LEN,
        commit_pow_bits: 0,
        query_pow_bits: QUERY_POW_BITS,
        num_queries: NUM_QUERIES,
        index_bits: DEGREE_BITS + LOG_BLOWUP,
        log_blowup: LOG_BLOWUP,
        max_log_arity: MAX_LOG_ARITY,
    };
    let (mut ch, log) = recorder();
    fri_shape.domain_separator::<Val, Challenge>().seed(&mut ch);
    let fri = log.lock().unwrap().clone();
    (stark, pcs, fri)
}

fn constants(out: &mut String) {
    let d = DEGREE_BITS;
    writeln!(out, "// SPDX-License-Identifier: MIT").unwrap();
    writeln!(out, "pragma solidity ^0.8.24;").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "// Generated by tools/src/bin/spend.rs from Plonky3 0.8.0 and ostra-swap-circuit. Do not edit.").unwrap();
    writeln!(out, "library SpendConstants {{").unwrap();
    writeln!(out, "    uint256 internal constant GENERATOR = {};", canon(Val::GENERATOR)).unwrap();
    let (stark, pcs, fri) = seeds();
    writeln!(out, "    bytes internal constant SEED_STARK = hex\"{}\";", hex(&stark)).unwrap();
    writeln!(out, "    bytes internal constant SEED_PCS = hex\"{}\";", hex(&pcs)).unwrap();
    writeln!(out, "    bytes internal constant SEED_FRI = hex\"{}\";", hex(&fri)).unwrap();
    let sched = schedule();
    let packed: usize = sched.iter().enumerate().map(|(i, a)| a << (4 * i)).sum();
    writeln!(out, "    // Folding schedule {:?}, one log-arity per 4 bits, round 0 lowest.", sched).unwrap();
    writeln!(out, "    uint256 internal constant ROUNDS = {};", sched.len()).unwrap();
    writeln!(out, "    uint256 internal constant ARITIES = 0x{:x};", packed).unwrap();
    // The initial trace domain: shift 1, 2^(d - 1) points, generator g.
    let g = Val::two_adic_generator(d - 1);
    writeln!(out, "    uint256 internal constant TRACE_GEN = {};", canon(g)).unwrap();
    writeln!(out, "    uint256 internal constant TRACE_GEN_INV = {};", canon(g.inverse())).unwrap();
    // Quotient chunks (as p3_uni_stark::verify builds them).
    let trace_domain = TwoAdicMultiplicativeCoset::new(Val::ONE, d).unwrap();
    let qd = trace_domain.try_create_disjoint_domain(1 << (d + 2)).unwrap();
    let chunks = qd.split_domains(QUOTIENT_CHUNKS);
    let mut cs = Vec::new();
    let mut ds = Vec::new();
    for (i, di) in chunks.iter().enumerate() {
        assert_eq!(di.log_size(), d - 1);
        cs.push(di.shift_inverse().exp_power_of_2(d - 1));
        let mut prod = Val::ONE;
        for (j, dj) in chunks.iter().enumerate() {
            if j != i {
                prod *= dj.vanishing_poly_at_point(di.first_point());
            }
        }
        ds.push(prod.inverse());
    }
    let list = |v: &[Val]| v.iter().map(|x| canon(*x).to_string()).collect::<Vec<String>>();
    writeln!(out, "    function chunkShiftPow() internal pure returns (uint256[8] memory) {{ return [{}]; }}", arr(&list(&cs))).unwrap();
    writeln!(out, "    function chunkDenomInv() internal pure returns (uint256[8] memory) {{ return [{}]; }}", arr(&list(&ds))).unwrap();
    // Periodic selectors as row bitmasks (bit r: one on row r), and the Lagrange weights
    // g^r / N used to evaluate them at zeta.
    let masks: Vec<String> = periodic_rows()
        .iter()
        .map(|rows| {
            let m: u128 = rows.iter().map(|&r| 1u128 << r).sum();
            format!("0x{:x}", m)
        })
        .collect();
    writeln!(out, "    function periodicMasks() internal pure returns (uint256[{}] memory) {{ return [{}]; }}", NUM_PERIODIC, arr(&masks)).unwrap();
    let n_inv = Val::from_u32(ROWS as u32).inverse();
    writeln!(out, "    // 1 / N for the N = 2^{} trace rows (Lagrange weights g^r / N).", LOG_ROWS).unwrap();
    writeln!(out, "    uint256 internal constant ROWS_INV = {};", canon(n_inv)).unwrap();
    let zeros: Vec<String> = empty_roots().iter().map(|z| format!("bytes32(0x{})", hex(&pack_digest(z)))).collect();
    writeln!(out, "    // Roots of empty subtrees of the commitment tree, packed digests: zeros[0] is the empty leaf.").unwrap();
    writeln!(out, "    function emptyRoots() internal pure returns (bytes32[{}] memory) {{ return [{}]; }}", zeros.len(), zeros.join(", ")).unwrap();
    let gens: Vec<String> = (0..=Val::TWO_ADICITY).map(|k| canon(Val::two_adic_generator(k)).to_string()).collect();
    writeln!(out, "    function twoAdicGenerators() internal pure returns (uint256[{}] memory) {{ return [{}]; }}", gens.len(), arr(&gens)).unwrap();
    let flatrc = |rows: &[[Val; 16]]| arr(&rows.iter().flatten().map(|x| canon(*x).to_string()).collect::<Vec<String>>());
    writeln!(out, "    function rcInitial() internal pure returns (uint256[64] memory) {{ return [{}]; }}", flatrc(&KOALABEAR_POSEIDON2_RC_16_EXTERNAL_INITIAL)).unwrap();
    writeln!(out, "    function rcFinal() internal pure returns (uint256[64] memory) {{ return [{}]; }}", flatrc(&KOALABEAR_POSEIDON2_RC_16_EXTERNAL_FINAL)).unwrap();
    let internal: Vec<String> = KOALABEAR_POSEIDON2_RC_16_INTERNAL.iter().map(|x| canon(*x).to_string()).collect();
    writeln!(out, "    function rcPartial() internal pure returns (uint256[20] memory) {{ return [{}]; }}", arr(&internal)).unwrap();
    let mut diag = Vec::new();
    for i in 0..16 {
        let mut s = [Val::ZERO; 16];
        s[i] = Val::ONE;
        GenericPoseidon2LinearLayersKoalaBear::internal_linear_layer(&mut s);
        for (j, v) in s.iter().enumerate() {
            if j != i {
                assert_eq!(*v, Val::ONE, "off-diagonal entries are 1");
            }
        }
        diag.push(canon(s[i] - Val::ONE).to_string());
    }
    writeln!(out, "    function internalDiag() internal pure returns (uint256[16] memory) {{ return [{}]; }}", arr(&diag)).unwrap();
    writeln!(out, "}}").unwrap();
}

fn packed(e: &Challenge) -> String {
    let c: &[Val] = BasedVectorSpace::<Val>::as_basis_coefficients_slice(e);
    let mut s = String::from("0x");
    for i in (0..EXT).rev() {
        write!(s, "{:08x}", c[i].as_canonical_u32()).unwrap();
    }
    s
}

fn rand_val(rng: &mut StdRng) -> Val {
    Val::from_u32(rng.next_u32() % Val::ORDER_U32)
}

fn rand_ext(rng: &mut StdRng) -> Challenge {
    let c: Vec<Val> = (0..EXT).map(|_| rand_val(rng)).collect();
    Challenge::from_basis_coefficients_slice(&c).unwrap()
}

fn list_packed(v: &[Challenge]) -> String {
    arr(&v.iter().map(packed).collect::<Vec<String>>())
}

// Differential vectors: the AIR's folded constraints (VerifierConstraintFolder) on random openings,
// periodic values and selectors at zeta, and the quotient recomposition, each by Plonky3's own code.
fn parts_vectors(out: &mut String) {
    let mut rng = StdRng::seed_from_u64(0x05EA_5EED);
    let air = SpendAir::new();
    writeln!(out, "// SPDX-License-Identifier: MIT").unwrap();
    writeln!(out, "pragma solidity ^0.8.24;").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "// Generated by tools/src/bin/spend.rs from Plonky3 0.8.0. Do not edit.").unwrap();
    writeln!(out, "// Extension elements are packed: coefficient i in bits [32 i, 32 i + 32).").unwrap();
    writeln!(out, "library SpendPartsVectors {{").unwrap();
    let init = TwoAdicMultiplicativeCoset::new(Val::ONE, DEGREE_BITS - 1).unwrap();
    for case in 0..3 {
        let local: Vec<Challenge> = (0..TRACE_WIDTH).map(|_| rand_ext(&mut rng)).collect();
        let next: Vec<Challenge> = (0..TRACE_WIDTH).map(|_| rand_ext(&mut rng)).collect();
        let pv: Vec<Val> = (0..NUM_PUBLIC).map(|_| rand_val(&mut rng)).collect();
        let zeta = rand_ext(&mut rng);
        let sels = init.selectors_at_point(zeta);
        let periodic = init.evaluate_periodic_columns_at(
            p3_commit::PeriodicColumns::new(&air.periodic_columns(), init.size()).unwrap(),
            zeta,
        );
        let alpha = rand_ext(&mut rng);
        let empty: [Challenge; 0] = [];
        let mut folder = VerifierConstraintFolder::<Config> {
            main: VerticalPair::new(RowMajorMatrixView::new_row(&local), RowMajorMatrixView::new_row(&next)),
            preprocessed: VerticalPair::new(RowMajorMatrixView::new(&empty, 0), RowMajorMatrixView::new(&empty, 0)),
            preprocessed_window: RowWindow::from_two_rows(&empty, &empty),
            periodic_values: &periodic,
            public_values: &pv,
            is_first_row: sels.is_first_row,
            is_last_row: sels.is_last_row,
            is_transition: sels.is_transition,
            alpha,
            accumulator: Challenge::ZERO,
        };
        air.eval(&mut folder);
        let pvs: Vec<String> = pv.iter().map(|x| canon(*x).to_string()).collect();
        writeln!(out, "    function local{case}() internal pure returns (uint256[{TRACE_WIDTH}] memory) {{ return [{}]; }}", list_packed(&local)).unwrap();
        writeln!(out, "    function next{case}() internal pure returns (uint256[{TRACE_WIDTH}] memory) {{ return [{}]; }}", list_packed(&next)).unwrap();
        writeln!(out, "    function publics{case}() internal pure returns (uint256[{NUM_PUBLIC}] memory) {{ return [{}]; }}", arr(&pvs)).unwrap();
        writeln!(out, "    function periodic{case}() internal pure returns (uint256[{NUM_PERIODIC}] memory) {{ return [{}]; }}", list_packed(&periodic)).unwrap();
        writeln!(out, "    uint256 internal constant ZETA_{case} = {};", packed(&zeta)).unwrap();
        writeln!(out, "    uint256 internal constant ALPHA_{case} = {};", packed(&alpha)).unwrap();
        writeln!(out, "    uint256 internal constant FIRST_{case} = {};", packed(&sels.is_first_row)).unwrap();
        writeln!(out, "    uint256 internal constant TRANSITION_{case} = {};", packed(&sels.is_transition)).unwrap();
        writeln!(out, "    uint256 internal constant INV_VANISHING_{case} = {};", packed(&sels.inv_vanishing)).unwrap();
        writeln!(out, "    uint256 internal constant FOLD_{case} = {};", packed(&folder.accumulator)).unwrap();
    }
    let zeta = rand_ext(&mut rng);
    let trace_domain = TwoAdicMultiplicativeCoset::new(Val::ONE, DEGREE_BITS).unwrap();
    let chunks_domains = trace_domain.try_create_disjoint_domain(1 << (DEGREE_BITS + 2)).unwrap().split_domains(QUOTIENT_CHUNKS);
    let chunks: Vec<Vec<Challenge>> = (0..QUOTIENT_CHUNKS).map(|_| (0..EXT).map(|_| rand_ext(&mut rng)).collect()).collect();
    let q = recompose_quotient_from_chunks::<Config>(&chunks_domains, &chunks, zeta);
    let flatc: Vec<Challenge> = chunks.iter().flatten().copied().collect();
    writeln!(out, "    uint256 internal constant QZETA = {};", packed(&zeta)).unwrap();
    writeln!(out, "    function chunks() internal pure returns (uint256[64] memory) {{ return [{}]; }}", list_packed(&flatc)).unwrap();
    writeln!(out, "    uint256 internal constant QUOTIENT = {};", packed(&q)).unwrap();
    writeln!(out, "}}").unwrap();
}

// Offsets of the variable-length sections of a flat proof, found by walking it as the decoder does.
struct Layout {
    commits: usize,
    final_poly: usize,
    query_pow: usize,
    batches: Vec<(usize, usize)>,
    rounds: Vec<(usize, usize)>,
}

fn layout(d: &[u8]) -> Layout {
    let arities = schedule();
    let commits = flat::O_COMMITS;
    let final_poly = commits + 32 * arities.len();
    let query_pow = final_poly + 32 * FINAL_POLY_LEN;
    let mut o = query_pow + 4;
    let mut batches = Vec::new();
    for widths in batch_widths() {
        let start = o;
        o += NUM_QUERIES * widths.iter().map(|w| 4 * (w + SALT)).sum::<usize>();
        let n = u16::from_be_bytes([d[o], d[o + 1]]) as usize;
        batches.push((start, o));
        o += 2 + 32 * n;
    }
    let mut rounds = Vec::new();
    for &a in &arities {
        let start = o;
        o += NUM_QUERIES * (32 * ((1 << a) - 1) + 4 * SALT);
        let n = u16::from_be_bytes([d[o], d[o + 1]]) as usize;
        rounds.push((start, o));
        o += 2 + 32 * n;
    }
    assert_eq!(o, d.len());
    Layout { commits, final_poly, query_pow, batches, rounds }
}

enum Edit {
    Xor(usize, u8),
    AddP(usize),
    AddOne(usize),
    Set(usize, Vec<u8>),
    Truncate(usize),
    Append(Vec<u8>),
    Public(usize),
}

fn apply(base: &[u8], e: &Edit) -> Vec<u8> {
    let mut v = base.to_vec();
    let u32_at = |v: &[u8], o: usize| u32::from_be_bytes([v[o], v[o + 1], v[o + 2], v[o + 3]]);
    match e {
        Edit::Xor(o, m) => v[*o] ^= m,
        Edit::AddP(o) => {
            let x = u32_at(&v, *o) + Val::ORDER_U32;
            v[*o..*o + 4].copy_from_slice(&x.to_be_bytes());
        }
        Edit::AddOne(o) => {
            let x = (u32_at(&v, *o) + 1) % Val::ORDER_U32;
            v[*o..*o + 4].copy_from_slice(&x.to_be_bytes());
        }
        Edit::Set(o, b) => v[*o..*o + b.len()].copy_from_slice(b),
        Edit::Truncate(n) => v.truncate(*n),
        Edit::Append(b) => v.extend_from_slice(b),
        Edit::Public(_) => {}
    }
    v
}

// Plonky3's verdict on a flat proof with its public values: decode (rejecting what Plonky3 cannot
// represent) and run p3_uni_stark::verify. None: the encoding has no Plonky3 counterpart.
fn oracle(flat: &[u8], pv: &[Val]) -> Option<bool> {
    let decoded = flat::decode(flat).ok()?;
    let ok = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| verify(&decoded, pv)));
    Some(ok.unwrap_or(false))
}

// Record: u8 op (0 replace, 1 truncate, 2 append, 3 public value + 1), u32 offset (or public index),
// u16 length, the bytes, u8 oracle (1 Plonky3 decides, 0 by design), u8 expected verdict (0).
fn tamper_cases(f: &[u8], pv: &[Val]) -> (Vec<u8>, usize, usize) {
    use flat::{O_BPW, O_QC, O_QUOT, O_RAND, O_RCW, O_RV, O_TL, O_TN, O_TRACE};
    let l = layout(f);
    let mut edits: Vec<(&str, Edit)> = vec![
        ("trace root", Edit::Xor(O_TRACE + 31, 1)),
        ("quotient root", Edit::Xor(O_QUOT, 0x80)),
        ("random root", Edit::Xor(O_RAND + 7, 4)),
        ("trace value", Edit::AddOne(O_TL + 28)),
        ("trace value high coefficient", Edit::AddOne(O_TL + 32 * 100)),
        ("trace value last column", Edit::AddOne(O_TL + 32 * (TRACE_WIDTH - 1) + 28)),
        ("next-row value", Edit::AddOne(O_TN + 28)),
        ("next-row value of a link column", Edit::AddOne(O_TN + 32 * C_W + 28)),
        ("quotient chunk value", Edit::AddOne(O_QC + 32 * 13 + 28)),
        ("random value", Edit::AddOne(O_RV + 32 * 3 + 12)),
        ("random codeword of random", Edit::AddOne(O_RCW + 28)),
        ("random codeword of trace at zeta", Edit::AddOne(O_RCW + 32 * 9 + 28)),
        ("random codeword of trace at zeta g", Edit::AddOne(O_RCW + 32 * 17 + 28)),
        ("random codeword of quotient", Edit::AddOne(O_RCW + 32 * 87 + 28)),
        ("batch witness", Edit::AddOne(O_BPW)),
        ("final polynomial", Edit::AddOne(l.final_poly + 32 * 15 + 28)),
        ("final polynomial constant", Edit::AddOne(l.final_poly + 28)),
        ("query witness", Edit::AddOne(l.query_pow)),
        ("truncated", Edit::Truncate(f.len() - 1)),
        ("trailing byte", Edit::Append(vec![0])),
        ("non-canonical trace value", Edit::AddP(O_TL + 28)),
        ("non-canonical next-row value", Edit::AddP(O_TN + 28)),
        ("non-canonical batch witness", Edit::AddP(O_BPW)),
        ("non-canonical final polynomial", Edit::AddP(l.final_poly + 28)),
        ("non-canonical query witness", Edit::AddP(l.query_pow)),
    ];
    for k in [PV_ASSET, PV_V, PV_FEE + 4, PV_NF + 3, PV_ROOT + 7, PV_CHANGE, PV_BIND + 7] {
        edits.push(("public value", Edit::Public(k)));
    }
    for r in 0..schedule().len() {
        edits.push(("fri commitment", Edit::Xor(l.commits + 32 * r + 5, 0x10)));
    }
    for (b, &(start, sib)) in l.batches.iter().enumerate() {
        let ws = &batch_widths()[b];
        edits.push(("input row first value", Edit::AddOne(start)));
        edits.push(("input row value of a later query", Edit::AddOne(start + 4 * (5 * (ws.iter().sum::<usize>() + SALT * ws.len()) + 3))));
        edits.push(("input salt", Edit::AddOne(start + 4 * ws[0])));
        edits.push(("input sibling first", Edit::Xor(sib + 2, 1)));
        edits.push(("input sibling count", Edit::Set(sib, vec![0, 0])));
        edits.push(("non-canonical input value", Edit::AddP(start)));
        edits.push(("non-canonical input salt", Edit::AddP(start + 4 * ws[0])));
    }
    for &(start, sib) in &l.rounds {
        edits.push(("commit sibling value", Edit::AddOne(start + 28)));
        edits.push(("commit sibling value of a later query", Edit::AddOne(start + 7 * 32 + 4)));
        edits.push(("commit salt", Edit::AddOne(sib - 4)));
        edits.push(("commit sibling digest", Edit::Xor(sib + 2 + 31, 2)));
        edits.push(("non-canonical commit sibling value", Edit::AddP(start + 28)));
        edits.push(("non-canonical commit salt", Edit::AddP(sib - 4)));
    }
    let mut out = Vec::new();
    let mut by_oracle = 0;
    let mut by_design = 0;
    for (name, e) in &edits {
        let v = apply(f, e);
        let mut pv2 = pv.to_vec();
        if let Edit::Public(k) = e {
            pv2[*k] += Val::ONE;
        }
        let verdict = oracle(&v, &pv2);
        assert_ne!(verdict, Some(true), "Plonky3 accepts the tampered case {name}");
        match verdict {
            Some(_) => by_oracle += 1,
            None => by_design += 1,
        }
        let (op, off, bytes): (u8, usize, Vec<u8>) = match e {
            Edit::Truncate(n) => (1, *n, vec![]),
            Edit::Append(b) => (2, f.len(), b.clone()),
            Edit::Xor(o, _) => (0, *o, v[*o..*o + 1].to_vec()),
            Edit::AddP(o) | Edit::AddOne(o) => (0, *o, v[*o..*o + 4].to_vec()),
            Edit::Set(o, b) => (0, *o, b.clone()),
            Edit::Public(k) => (3, *k, vec![]),
        };
        out.push(op);
        out.extend_from_slice(&(off as u32).to_be_bytes());
        out.extend_from_slice(&(bytes.len() as u16).to_be_bytes());
        out.extend_from_slice(&bytes);
        out.push(verdict.is_some() as u8);
        out.push(0);
    }
    (out, by_oracle, by_design)
}

