# Writes sdk/src/abi.ts from the Foundry build (out/): the ABIs of OstraRouter, OstraStake, OstraBuyback and OstraPrivatePool,
# OstraSwapEscrow's creation code (an escrow's address is CREATE2 of it) and OstraQuoteBatch (route.ts's quotes). Run after `forge build`.
import json, os, sys
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
def art(f, c):
    return json.load(open(os.path.join(root, 'out', f, c + '.json')))
out = ['// Generated by sdk/scripts/abi.py from the Foundry build (out/). Do not edit.', '']
for f, c, name in (('OstraRouter.sol', 'OstraRouter', 'ostraRouterAbi'), ('OstraStake.sol', 'OstraStake', 'ostraStakeAbi'), ('OstraBuyback.sol', 'OstraBuyback', 'ostraBuybackAbi'), ('OstraPrivatePool.sol', 'OstraPrivatePool', 'ostraPrivatePoolAbi')):
    out.append(f'export const {name} = {json.dumps(art(f, c)["abi"], indent=2)} as const;')
    out.append('')
code = art('OstraRouter.sol', 'OstraSwapEscrow')['bytecode']['object']
assert code.startswith('0x') and len(code) > 2
out.append('/** OstraSwapEscrow\'s creation code (without constructor arguments). */')
out.append(f'export const OSTRA_SWAP_ESCROW_CREATION_CODE = "{code}" as const;')
out.append('')
batch = art('OstraQuoteBatch.sol', 'OstraQuoteBatch')
assert batch['bytecode']['object'].startswith('0x') and len(batch['bytecode']['object']) > 2
out.append(f'export const ostraQuoteBatchAbi = {json.dumps(batch["abi"], indent=2)} as const;')
out.append('')
out.append('/** OstraQuoteBatch\'s creation code: run in an eth_call without `to`, never deployed (route.ts). */')
out.append(f'export const OSTRA_QUOTE_BATCH_CREATION_CODE = "{batch["bytecode"]["object"]}" as const;')
out.append('')
open(os.path.join(root, 'sdk', 'src', 'abi.ts'), 'w').write('\n'.join(out))
print('wrote sdk/src/abi.ts', len(code) // 2 - 1, 'bytes of escrow creation code')
